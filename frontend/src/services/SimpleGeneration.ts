    config.onLog('[SimpleGeneration] Step 1.5: Tech Lead translating plan...');
    config.onLog(`[SimpleGeneration] Artist layer ready: ${JSON.stringify((plan as { artistLayer?: ArtistLayerSpec }).artistLayer ?? {}).slice(0, 240)}`);

