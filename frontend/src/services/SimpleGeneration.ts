/**
 * Strips internal markers from raw LLM output to produce a clean user-facing message.
 * Removes: <think>…</think>, <!--FILE:…--> blocks, fenced code blocks.
 * Falls back to a safe default when nothing meaningful remains.
 */
function cleanCoderMessage(raw: string, fallback = 'Generated files and updated preview.'): string {
  let text = raw;
  // 1. Strip <think>…</think> blocks (greedy, may span multiple lines)
  text = text.replace(/<think>[\s\S]*?<\/think>/gi, '');
  // 2. Strip <!--FILE:…--> markers and their content until the next marker or end
  text = text.replace(/<!--FILE:[\s\S]*?(?=<!--FILE:|<!--\/FILE-->|$)/g, '');
  text = text.replace(/<!--\/FILE-->/g, '');
  // 3. Strip fenced code blocks (```…```)
  text = text.replace(/```[\s\S]*?```/g, '');
  // 4. Strip leftover markdown headings that are just section labels
  text = text.replace(/^##\s+[^\n]*$/gm, '');
  // 5. Collapse whitespace
  text = text.replace(/\n{3,}/g, '\n\n').trim();
  return text.length > 5 ? text.slice(0, 300) : fallback;
}

function djb2(s: string): string {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(16);
}

