/**
 * Classify and gate a candidate before it is compiled.
 *
 * Called once per compile cycle — AFTER all candidate files are buffered,
 * BEFORE compileWithRetry. If the edit is classified as risky or destructive
 * and `config.waitForAdmission` is set, the user is prompted to confirm.
 *
 * Returns true  → proceed with compile.
 * Returns false → caller must rollback + abort.
 */
async function runAdmissionCheck(
  revId: string,
  source: string,
  config: PipelineRunConfig,
  candidatePathsOverride?: string[],
): Promise<boolean> {
  const candidateFiles  = revisionManager.getRevisionFiles(revId) ?? {};
  const activeId        = revisionManager.getActiveRevisionId();
  const activeFiles     = activeId ? (revisionManager.getRevisionFiles(activeId) ?? {}) : {};

  const decision = EditAdmissionService.classify({
    candidatePaths: candidatePathsOverride ?? Object.keys(candidateFiles),
    activePaths:    Object.keys(activeFiles),
    source,
  });

  const approved = await resolveAdmissionDecision(
    decision,
    config.waitForAdmission,
    config.onLog,
  );
  if (!approved) {
    config.onLog('[AdmissionControl] edit rejected by user — rolling back candidate');
  }
  return approved;
}

/**
 * Detects if a file's content is actually a full artifact envelope JSON
 * rather than real source code. This is a critical guard — if the LLM
 * returns the entire response structure as the body of a single file,
 * we must skip it to prevent writing JSON blobs to preview-workspace.
 */
function looksLikeArtifactEnvelope(value: string): boolean {
  const t = value.trim();
  if (!t.startsWith('{') || !t.endsWith('}')) return false;
  return /"artifact"\s*:/.test(t) && /"files"\s*:/.test(t) &&
         /"path"\s*:/.test(t) && /"content"\s*:/.test(t);
}

function toDependencySpecs(deps: string[]): DependencySpec[] {
  return deps
    .map((raw) => raw.trim())
    .filter(Boolean)
    .map((raw) => {
      let name = raw;
      let version: string | undefined;

      if (raw.startsWith('@')) {
        const splitAt = raw.lastIndexOf('@');
        if (splitAt > 0) {
          name = raw.slice(0, splitAt);
          version = raw.slice(splitAt + 1) || undefined;
        }
      } else if (raw.includes('@')) {
        const [pkg, ...rest] = raw.split('@');
        name = pkg;
        version = rest.join('@') || undefined;
      }

      return {
        id: `npm:${name}`,
        name,
        kind: 'npm' as const,
        version,
        importedBy: [],
        isDevDependency: false,
      };
    });
}

function mergeDependencySpecs(...groups: Array<DependencySpec[] | undefined>): DependencySpec[] {
  const merged = new Map<string, DependencySpec>();

  for (const group of groups) {
    for (const dep of group ?? []) {
      if (!dep?.id) continue;
      merged.set(dep.id, merged.has(dep.id)
        ? {
            ...merged.get(dep.id)!,
            ...dep,
            importedBy: Array.from(new Set([
              ...(merged.get(dep.id)?.importedBy ?? []),
              ...(dep.importedBy ?? []),
            ])),
          }
        : dep);
    }
  }

  return Array.from(merged.values());
}

