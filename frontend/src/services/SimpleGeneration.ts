// ─── FILE Marker Parser ─────────────────────────────────────────────────────

/**
 * Strip markdown code fences from a string.
 * Handles: ```tsx\n...\n``` , ```typescript\n...\n``` , ```\n...\n```
 * Works on both outer wrapper and inner per-file fences.
 */
function stripFences(text: string): string {
  let s = text.trim();
  // Strip opening fence: ```lang\n or ```\n
  s = s.replace(/^```\w*\n?/, '');
  // Strip closing fence: \n``` at end
  s = s.replace(/\n?```\s*$/, '');
  return s.trim();
}

function extractFirstJsonObject(raw: string): string | null {
  const text = stripFences(raw);
  const start = text.indexOf('{');
  if (start < 0) return null;

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let i = start; i < text.length; i++) {
    const ch = text[i];

    if (inString) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }

    if (ch === '"') {
      inString = true;
      continue;
    }
    if (ch === '{') depth++;
    if (ch === '}') {
      depth--;
      if (depth === 0) return text.slice(start, i + 1);
    }
  }
  return null;
}


