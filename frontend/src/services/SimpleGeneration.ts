  /**
   * Lightweight pre-generation step: ask the LLM whether the user's request
   * is specific enough to build directly, or whether 1-2 clarifying questions
   * would help. Returns null if the intent is already clear or if the call
   * fails (network error, parse error) — callers should treat null as "skip".
   */
  static async clarify(config: {
    intent:  string;
    apiKey:  string;
    signal?: AbortSignal;
  }): Promise<{ questions: string[] } | null> {
    const CLARIFIER_PROMPT = `You are a product advisor. The user wants to build an app.

Analyze their request. If it's clear and specific enough to build — respond with:
{"clear": true}

If it's vague or would benefit from clarification — respond with:
{"clear": false, "questions": ["question1", "question2"]}

RULES:
- Maximum 2 questions. Keep them short and specific.
- Ask about WHAT the app does, not HOW to build it.
- If the user already described features, pages, or specific functionality — it's clear.
- If it's just a category ("fitness app", "todo app") — ask what features.
- Questions should offer concrete options, not open-ended.
- Respond ONLY with JSON. No markdown, no explanation.

EXAMPLES:
User: "fitness app" → {"clear": false, "questions": ["What should it track — workouts, meals, weight, or all three?", "Should it have a social feature like sharing progress?"]}
User: "task manager with projects, tags, and due dates" → {"clear": true}
User: "restaurant app" → {"clear": false, "questions": ["Is this for customers (menu, ordering, reviews) or for staff (table management, orders)?", "Should it support online ordering and delivery?"]}
User: "pregnancy tracker with weekly updates and symptom log" → {"clear": true}`;

    let raw: string;
    try {
      raw = await callLLM(
        CLARIFIER_PROMPT,
        config.intent,
        'primary',
        config.apiKey,
        undefined,
        config.signal,
        ConfigService.getMaxTokens('agent_primary', 'clarifier'),
      );
    } catch (err) {
      // Re-throw user aborts so the caller's abort handling works correctly.
      if (err instanceof DOMException && err.name === 'AbortError') throw err;
      return null; // network / timeout error → skip clarification silently
    }
    try {
      const cleaned = raw.trim().replace(/^```json?\s*\n?/, '').replace(/\n?```\s*$/, '');
      const parsed: unknown = JSON.parse(cleaned);
      if (typeof parsed !== 'object' || parsed === null) return null;
      const p = parsed as Record<string, unknown>;
      if (p['clear'] === true) return null;
      const qs = Array.isArray(p['questions'])
        ? (p['questions'] as unknown[]).filter((q): q is string => typeof q === 'string')
        : [];
      return qs.length > 0 ? { questions: qs } : null;
    } catch {
      return null; // JSON parse failure → skip clarification
    }
  }

