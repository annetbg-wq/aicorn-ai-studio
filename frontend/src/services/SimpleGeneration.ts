// ─── File Validator ─────────────────────────────────────────────────────────

/**
 * Returns false if the file content is too short, missing code keywords,
 * or has severely mismatched braces (strong sign the LLM truncated output).
 */
function validateFile(path: string, content: string): boolean {
  if (!content || content.trim().length < 20) return false;
  if ((path.endsWith('.tsx') || path.endsWith('.ts')) &&
      !/(?:export|import|function|const)\s/.test(content)) return false;
  const opens  = (content.match(/\{/g) || []).length;
  const closes = (content.match(/\}/g) || []).length;
  if (opens > 0 && Math.abs(opens - closes) > 5) return false;
  return true;
}

