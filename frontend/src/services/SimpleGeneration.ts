/**
 * Sends an image to the spec-slot model and returns a structured JSON
 * description of the design (color scheme, navigation, components, etc.).
 * Returns '' on any error so callers can degrade gracefully.
 */
async function analyzeImageWithVision(
  imageDataUri: string,
  mimeType: string,
  fallbackApiKey: string,
  onLog?: (msg: string) => void,
  signal?: AbortSignal,
): Promise<string> {
  onLog?.('[Intake] Analyzing image with Vision...');

  const modelId  = ConfigService.resolveModel('spec');
  const apiKey   = ConfigService.getKeyForAgent('spec') || fallbackApiKey;
  const provider = ConfigService.getAgentConfig('agent_spec').provider || 'openrouter';
  const endpoint = Orchestrator.getEndpoint(provider);

  const body = JSON.stringify({
    model: modelId,
    messages: [{
      role: 'user',
      content: [
        { type: 'image_url', image_url: { url: imageDataUri } },
        {
          type: 'text',
          text: `Analyze this screenshot/design reference and extract:
1. App type (what kind of application is this?)
2. Color scheme (primary colors, background color, accent color — give hex codes)
3. Navigation pattern (top bar, bottom tabs, sidebar, none)
4. Key UI components visible (cards, lists, charts, forms, etc.)
5. Layout density (compact/comfortable/spacious)
6. Overall visual style (minimal, colorful, dark, light, etc.)

Respond in JSON format:
{
  "appType": "...",
  "colorScheme": { "background": "#...", "primary": "#...", "accent": "#..." },
  "navigation": "top-nav|bottom-tabs|sidebar|none",
  "components": ["card", "list", ...],
  "density": "compact|comfortable|spacious",
  "style": "...",
  "summary": "One sentence describing this design"
}`,
        },
      ],
    }],
    stream: false,
    temperature: 0.2,
    max_tokens: 1000,
  });

  const headers = {
    'Authorization': `Bearer ${apiKey}`,
    'Content-Type':  'application/json',
    'HTTP-Referer':  window.location.origin,
  };

  try {
    if (signal?.aborted) throw new DOMException('Aborted', 'AbortError');
    const resp = await llmFetch(endpoint, headers, body);
    const data = await resp.json() as { choices?: Array<{ message?: { content?: string } }> };
    const text = (data.choices?.[0]?.message?.content ?? '').trim();
    onLog?.(`[Intake] Vision analysis complete: ${text.slice(0, 120)}`);
    return text;
  } catch (e) {
    if (e instanceof DOMException && e.name === 'AbortError') throw e;
    onLog?.(`[Intake] Vision API error: ${e}`);
    return '';
  }
}

// ─── File Validator ─────────────────────────────────────────────────────────

/**
 * Returns false if the file content is too short, missing code keywords,
 * or has severely mismatched braces (strong sign the LLM truncated output).
 */
function validateFile(path: string, content: string): boolean {
  if (!content || content.trim().length < 20) return false;
  if ((path.endsWith('.tsx') || path.endsWith('.ts')) &&
      !/(?:export|import|function|const)\s/.test(content)) return false;
  const opens  = (content.match(/\{/g) || []).length;
  const closes = (content.match(/\}/g) || []).length;
  if (opens > 0 && Math.abs(opens - closes) > 5) return false;
  return true;
}

// ─── Error File Extractor ────────────────────────────────────────────────────

/**
 * Extracts the relative file path from a Vite error message.
 * Handles patterns like "src/pages/X.tsx", "/src/X.tsx", URL paths.
 */
function extractFileFromError(msg: string): string | null {
  const match = msg.match(/(?:src\/)([\w/.]+\.tsx?)/);
  return match ? match[1] : null;
}

// ─── shadcn Enforcer ────────────────────────────────────────────────────────

/**
 * Validates and auto-fixes LLM output to enforce shadcn/ui components and
 * design tokens. Mutates llmFiles in place.
 */
function enforceShadcn(llmFiles: Record<string, string>, onLog: (msg: string) => void): void {
  const allCode = Object.values(llmFiles).join('\n');
  const hasShadcn    = allCode.includes('@/components/ui/');
  const hasRawButtons = /<button[\s>]/.test(allCode);
  const hasRawInputs  = /<input[\s/]/.test(allCode);
  const hasRawColors  = /bg-(?:blue|green|red|indigo|purple|pink|yellow|orange)-[0-9]/.test(allCode);

  if (!hasShadcn || hasRawButtons || hasRawInputs || hasRawColors) {
    onLog(`[SimpleGeneration] ⚠ shadcn check: imports=${hasShadcn} rawButtons=${hasRawButtons} rawInputs=${hasRawInputs} rawColors=${hasRawColors}`);

    for (const [filePath, content] of Object.entries(llmFiles)) {
      let fixed = content;

      if (/<button[\s>]/.test(fixed)) {
        if (!fixed.includes('@/components/ui/button')) {
          fixed = `import { Button } from "@/components/ui/button";\n` + fixed;
        }
        // Simple tag-name swap — handles multi-line JSX attrs correctly
        fixed = fixed.replace(/<button(\s)/g, '<Button$1');
        fixed = fixed.replace(/<button>/g, '<Button>');
        fixed = fixed.replace(/<\/button>/g, '</Button>');
      }

      if (/<input[\s/]/.test(fixed)) {
        if (!fixed.includes('@/components/ui/input')) {
          fixed = `import { Input } from "@/components/ui/input";\n` + fixed;
        }
        fixed = fixed.replace(/<input(\s)/g, '<Input$1');
        fixed = fixed.replace(/<input\/>/g, '<Input />');
      }

      fixed = fixed.replace(/bg-gray-900/g,        'bg-background');
      fixed = fixed.replace(/bg-gray-800/g,         'bg-card');
      fixed = fixed.replace(/bg-gray-700/g,         'bg-muted');
      fixed = fixed.replace(/text-gray-100/g,       'text-foreground');
      fixed = fixed.replace(/text-gray-300/g,       'text-foreground');
      fixed = fixed.replace(/text-gray-400/g,       'text-muted-foreground');
      fixed = fixed.replace(/text-gray-500/g,       'text-muted-foreground');
      fixed = fixed.replace(/text-white/g,          'text-foreground');
      fixed = fixed.replace(/border-gray-[0-9]+/g,  'border-border');

      if (fixed !== content) {
        llmFiles[filePath] = fixed;
        onLog(`[SimpleGeneration] Auto-fixed: ${filePath}`);
      }
    }
  }
}

// ─── Blueprint formatter ────────────────────────────────────────────────────

function formatBlueprint(plan: any): string {
  const lines: string[] = [];
  const b = plan.blueprint;

  lines.push(`## ${plan.appName}`);
  lines.push(`_${plan.description}_`);
  lines.push('');

  if (plan.targetUser) {
    lines.push(`**Target user:** ${plan.targetUser}`);
    lines.push('');
  }

  if (plan.productStrategy) {
    lines.push('### Product Strategy');
    lines.push(`- **Core action:** ${plan.productStrategy.coreAction}`);
    lines.push(`- **Retention:** ${plan.productStrategy.retentionLoop}`);
    if (plan.productStrategy.paywall?.needed) {
      lines.push(`- **Monetization:** ${plan.productStrategy.paywall.trigger}`);
    }
    lines.push('');
  }

  if (plan.pages?.length) {
    lines.push('### Screens');
    plan.pages.forEach((p: any, i: number) => {
      const guard = p.guard ? ` _(${p.guard})_` : '';
      lines.push(`${i + 1}. **${p.name}** — ${p.purpose}${guard}`);
    });
    lines.push('');
  }

  if (b?.userJourney) {
    lines.push('### User Journey');
    lines.push(b.userJourney);
    lines.push('');
  }

  if (b?.stateMachine) {
    lines.push('### State Machine');
    lines.push(b.stateMachine);
    lines.push('');
  }

  if (b?.logicBlackBox) {
    lines.push('### Logic (Black Box)');
    lines.push(b.logicBlackBox);
    lines.push('');
  }

  if (b?.uiSpec) {
    lines.push('### UI Components');
    lines.push(b.uiSpec);
    lines.push('');
  }

  return lines.join('\n');
}

